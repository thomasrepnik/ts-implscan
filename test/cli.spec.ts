// Runs the CLI (dry run) against small projects written to a temp folder.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';

const MARKER = `export interface ImplScan {}
export interface Dispatchable<T> extends ImplScan { isApplicableTo(context: T): boolean; getPriority(): number; }`;

function runCli(files: Record<string, string>): { stdout: string; stderr: string; status: number | null } {
  const dir = mkdtempSync(path.join(tmpdir(), 'implscan-cli-'));
  writeFileSync(path.join(dir, 'tsconfig.json'), `{ "compilerOptions": { "module": "ES2022", "moduleResolution": "bundler", "strict": true } }`);
  for (const [file, text] of Object.entries({ 'src/marker.ts': MARKER, ...files })) {
    mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    writeFileSync(path.join(dir, file), text);
  }
  const out = path.join(dir, 'src/generated/implscan-registry.ts');
  const result = spawnSync(
    process.execPath,
    ['src/cli.ts', '--project', path.join(dir, 'tsconfig.json'), '--src', path.join(dir, 'src'), '--out', out, '--target', 'angular', '--dry-run'],
    { encoding: 'utf8' },
  );
  return { stdout: result.stdout, stderr: result.stderr, status: result.status };
}

const H = `import type { Dispatchable } from './marker';
export interface Ctx { method: string }
export interface H extends Dispatchable<Ctx> { pay(amount: number): string }`;
const IMPL = `import type { H } from './h';
export class Impl implements H { isApplicableTo() { return true; } getPriority() { return 0; } pay(amount: number) { return String(amount); } }`;

test('a previously generated file is not scanned, even with a line prepended to its header', () => {
  const { stdout, stderr } = runCli({
    'src/h.ts': H,
    'src/impl.ts': IMPL,
    'src/generated/implscan-registry.ts': `/* eslint-disable */
// GENERATED by ts-implscan – do not edit
import type { H } from '../h';
export class HDispatcher implements H { isApplicableTo() { return true; } getPriority() { return 0; } pay(amount: number) { return String(amount); } }
`,
  });
  assert.equal(stderr, '');
  assert.match(stdout, /export const HImplementations: Array<new \(\.\.\.args: any\[\]\) => H> = \[Impl\];/);
});

test('a dispatcher import that would rebind a registry interface name is dropped, the list keeps its own type', () => {
  const { stdout, stderr } = runCli({
    'src/types.ts': `export interface B { x: string }`,
    'src/a.ts': `import type { Dispatchable } from './marker';
import type { B } from './types';
export interface Ctx {}
export interface A extends Dispatchable<Ctx> { make(): B }`,
    'src/b.ts': `import type { ImplScan } from './marker';
export interface B extends ImplScan { ping(): void }`,
  });
  assert.match(stderr, /no dispatcher for A: .*B/);
  assert.match(stdout, /import type \{ B \} from '\.\.\/b';/);
  assert.doesNotMatch(stdout, /from '\.\.\/types'/);
  assert.doesNotMatch(stdout, /ADispatcher/);
});
