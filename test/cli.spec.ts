// Runs the CLI (dry run) against small projects written to a temp folder.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';

const MARKER = `export interface ImplScan {}
export interface Dispatchable<T = void> extends ImplScan { isApplicableTo(context: T): boolean; getPriority(): number; }
export interface DispatchContextProvider<T> { get(): T }`;

function runCli(files: Record<string, string>): { stdout: string; stderr: string; status: number | null } {
  const dir = mkdtempSync(path.join(tmpdir(), 'implscan-cli-'));
  writeFileSync(path.join(dir, 'tsconfig.json'), `{ "compilerOptions": { "module": "ES2022", "moduleResolution": "bundler", "strict": true } }`);
  for (const [file, text] of Object.entries({ 'src/marker.ts': MARKER, ...files })) {
    mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    writeFileSync(path.join(dir, file), text);
  }
  const out = path.join(dir, 'src/generated/implscan-registry.ts');
  const result = spawnSync(
    process.execPath,
    ['src/cli.ts', '--project', path.join(dir, 'tsconfig.json'), '--src', path.join(dir, 'src'), '--out', out, '--target', 'angular', '--dry-run'],
    { encoding: 'utf8' },
  );
  return { stdout: result.stdout, stderr: result.stderr, status: result.status };
}

const H = `import type { Dispatchable } from './marker';
export interface Ctx { method: string }
export interface H extends Dispatchable<Ctx> { pay(amount: number): string }`;
const IMPL = `import type { H } from './h';
export class Impl implements H { isApplicableTo() { return true; } getPriority() { return 0; } pay(amount: number) { return String(amount); } }`;

test('a previously generated file is not scanned, even with a line prepended to its header', () => {
  const { stdout, stderr } = runCli({
    'src/h.ts': H,
    'src/impl.ts': IMPL,
    'src/generated/implscan-registry.ts': `/* eslint-disable */
// GENERATED by ts-implscan – do not edit
import type { H } from '../h';
export class HDispatcher implements H { isApplicableTo() { return true; } getPriority() { return 0; } pay(amount: number) { return String(amount); } }
`,
  });
  assert.equal(stderr, '');
  assert.match(stdout, /export const HImplementations: Array<new \(\.\.\.args: any\[\]\) => H> = \[Impl\];/);
});

test('a dispatcher import that would rebind a registry interface name is dropped, the list keeps its own type', () => {
  const { stdout, stderr } = runCli({
    'src/types.ts': `export interface B { x: string }`,
    'src/a.ts': `import type { Dispatchable } from './marker';
import type { B } from './types';
export interface Ctx {}
export interface A extends Dispatchable<Ctx> { make(): B }`,
    'src/b.ts': `import type { ImplScan } from './marker';
export interface B extends ImplScan { ping(): void }`,
  });
  assert.match(stderr, /no dispatcher for A: .*B/);
  assert.match(stdout, /import type \{ B \} from '\.\.\/b';/);
  assert.doesNotMatch(stdout, /from '\.\.\/types'/);
  assert.doesNotMatch(stdout, /ADispatcher/);
});

test('a context-free interface gets a dispatcher but no context token', () => {
  const { stdout, stderr } = runCli({
    'src/f.ts': `import type { Dispatchable } from './marker';
export interface F extends Dispatchable { format(lines: string[]): string }`,
    'src/plain.ts': `import type { F } from './f';
export class PlainText implements F { isApplicableTo() { return true; } getPriority() { return 0; } format(lines: string[]) { return lines.join('\\n'); } }`,
  });
  assert.equal(stderr, '');
  assert.match(stdout, /export class FDispatcher implements F \{/);
  assert.match(stdout, /isApplicableTo\(\): boolean \{/);
  assert.doesNotMatch(stdout, /F_CONTEXT/);
  assert.match(stdout, /\{ provide: FDispatcher, useClass: FDispatcher \},/);
});

test('isApplicableTo redeclared in the interface stops the generation with an error', () => {
  const { stdout, stderr, status } = runCli({
    'src/p.ts': `import type { Dispatchable } from './marker';
export interface PaymentContext { method: string }
export interface PaymentHandler extends Dispatchable<PaymentContext> {
  isApplicableTo(context: PaymentContext): boolean;
  pay(): string;
}
export class CardHandler implements PaymentHandler {
  isApplicableTo() { return true; }
  getPriority() { return 0; }
  pay() { return 'card'; }
}`,
  });
  assert.equal(status, 1);
  assert.equal(stdout, '');
  assert.match(stderr, /^cannot generate: PaymentHandler .*isApplicableTo.*automatically.*must not/m);
});

const PROVIDER = `import type { DispatchContextProvider } from './marker';
import type { Ctx } from './h';
export class CtxProvider implements DispatchContextProvider<Ctx> { get() { return { method: 'card' }; } }`;

test('a DispatchContextProvider class is wired into provideImplscan', () => {
  const { stdout, stderr } = runCli({ 'src/h.ts': H, 'src/impl.ts': IMPL, 'src/ctx.provider.ts': PROVIDER });
  assert.equal(stderr, '');
  assert.match(stdout, /^import \{ CtxProvider \} from '\.\.\/ctx\.provider';$/m);
  const providers = stdout.slice(stdout.indexOf('export function provideImplscan'));
  assert.deepEqual(
    providers.split('\n').filter((l) => l.includes('provide:')),
    [
      `    { provide: H_LIST, useClass: Impl, multi: true },`,
      `    { provide: CtxProvider, useClass: CtxProvider },`,
      `    { provide: H_CONTEXT, useFactory: () => { const provider = inject(CtxProvider); return () => provider.get(); } },`,
      `    { provide: HDispatcher, useClass: HDispatcher },`,
    ],
  );
});

test('several providers for one context type warn and wire none', () => {
  const { stdout, stderr } = runCli({
    'src/h.ts': H,
    'src/impl.ts': IMPL,
    'src/a.provider.ts': PROVIDER.replace('CtxProvider', 'AProvider'),
    'src/b.provider.ts': PROVIDER.replace('CtxProvider', 'BProvider'),
  });
  assert.match(stderr, /several context providers for Ctx: AProvider, BProvider/);
  assert.doesNotMatch(stdout, /useFactory/);
  assert.match(stdout, /\{ provide: HDispatcher, useClass: HDispatcher \},/);
});
