#!/usr/bin/env node
// Build-time "component scan": finds every exported interface that extends the
// `ImplScan` or `Dispatchable` marker, then every exported class that implements one
// of them, and writes one array of implementations per interface. `Dispatchable`
// interfaces also get a dispatcher class. With `--target angular` it also writes an
// InjectionToken per interface (and per dispatcher context) and `provideImplscan()`.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { type ExpressionWithTypeArguments, type InterfaceDeclaration, Node, Project, ts, type TypeNode } from 'ts-morph';
import { analyzeDispatcher, DISPATCH_MARKER, RESOLVE_DELEGATE_SOURCE, renderDispatcher, TypeImports } from './dispatcher.ts';

const CONTEXT_PROVIDER = 'DispatchContextProvider';
const MARKERS = new Set(['ImplScan', DISPATCH_MARKER, CONTEXT_PROVIDER]);
const GENERATED_HEADER = '// GENERATED by ts-implscan';

const { values: args } = parseArgs({
  options: {
    project: { type: 'string', default: 'tsconfig.json' },
    src: { type: 'string', default: 'src' },
    out: { type: 'string', default: 'src/generated/implscan-registry.ts' },
    target: { type: 'string', default: 'plain' },
    'dry-run': { type: 'boolean', default: false },
    help: { type: 'boolean', short: 'h', default: false },
  },
});
if (args.help) {
  console.log(`Usage: ts-implscan [options]

  --project <file>   tsconfig to read compiler options from
                     (default: tsconfig.json)
  --src <dir>        folder to scan (default: src)
  --out <file>       file to generate
                     (default: src/generated/implscan-registry.ts)
  --target <target>  plain | angular (default: plain)
  --dry-run          print the result instead of writing it
  -h, --help         show this help`);
  process.exit(0);
}
if (args.target !== 'plain' && args.target !== 'angular') {
  console.error(`unknown --target '${args.target}', expected 'plain' or 'angular'`);
  process.exit(1);
}
const target = args.target;

const outFile = path.resolve(args.out);
const outDir = path.dirname(outFile);

// Use the tsconfig only for compiler options (paths, module resolution). Files come from
// a glob, because new implementations are not imported anywhere yet (Angular's
// tsconfig.app.json only lists main.ts).
const project = new Project({ tsConfigFilePath: args.project, skipAddingFilesFromTsConfig: true });
project.addSourceFilesAtPaths([`${args.src}/**/*.ts`, `!${args.src}/**/*.spec.ts`, `!${args.src}/**/*.d.ts`]);
// Generated files (the output file, and anything carrying the header near the top, e.g. a
// second registry) are never scanned, so a generated dispatcher is not an implementation.
const isGenerated = (text: string) => text.split('\n', 5).some((line) => line.startsWith(GENERATED_HEADER));
const sourceFiles = project.getSourceFiles().filter((f) => f.getFilePath() !== outFile && !isGenerated(f.getFullText()));

// Pick the import extension the tsconfig expects: `.ts` (Node type stripping),
// `.js` (NodeNext) or none (Angular's `bundler` resolution).
const options = project.getCompilerOptions();
const importExt = options.allowImportingTsExtensions
  ? '.ts'
  : options.moduleResolution === ts.ModuleResolutionKind.Node16 ||
      options.moduleResolution === ts.ModuleResolutionKind.NodeNext
    ? '.js'
    : '';

// resolve through the type checker so aliased/renamed imports still match
function resolveInterface(clause: ExpressionWithTypeArguments) {
  let symbol = clause.getExpression().getSymbol();
  if (symbol?.isAlias()) symbol = symbol.getAliasedSymbol();
  return symbol?.getDeclarations().find(Node.isInterfaceDeclaration);
}

const keyOf = (decl: InterfaceDeclaration) => `${decl.getSourceFile().getFilePath()}#${decl.getName()}`;

type Ref = { name: string; file: string };
type Entry = { iface: Ref; impls: Ref[]; decl: InterfaceDeclaration; marker?: ExpressionWithTypeArguments };
const registry = new Map<string, Entry>();
// context type (see contextKey) -> classes implementing DispatchContextProvider<that type>
const contextProviders = new Map<string, Ref[]>();

// Identity of a named context type, so that `Dispatchable<PaymentContext>` and
// `DispatchContextProvider<PaymentContext>` meet. Inline literal types never match.
function contextKey(typeNode: TypeNode | undefined) {
  const type = typeNode?.getType();
  const symbol = type?.getAliasSymbol() ?? type?.getSymbol();
  const decl = symbol?.getDeclarations()[0];
  if (!symbol || !decl || symbol.getName() === '__type') return undefined;
  return `${decl.getSourceFile().getFilePath()}#${symbol.getName()}`;
}

// 1. interfaces that opt in by extending a marker directly
for (const sourceFile of sourceFiles) {
  for (const iface of sourceFile.getInterfaces()) {
    if (!iface.isExported() || MARKERS.has(iface.getName())) continue;
    const markers = iface.getExtends().map((clause) => [clause, resolveInterface(clause)?.getName()] as const);
    if (!markers.some(([, name]) => name !== undefined && MARKERS.has(name))) continue;
    const marker = markers.find(([, name]) => name === DISPATCH_MARKER)?.[0];
    registry.set(keyOf(iface), { iface: { name: iface.getName(), file: sourceFile.getFilePath() }, impls: [], decl: iface, marker });
  }
}

// 2. classes implementing one of those interfaces
for (const sourceFile of sourceFiles) {
  for (const cls of sourceFile.getClasses()) {
    const name = cls.getName();
    if (!name || cls.isAbstract()) continue;

    for (const clause of cls.getImplements()) {
      const decl = resolveInterface(clause);
      const providerKey = decl?.getName() === CONTEXT_PROVIDER ? contextKey(clause.getTypeArguments()[0]) : undefined;
      const entry = decl && registry.get(keyOf(decl));
      if (!entry && !providerKey) continue;
      if (!cls.isExported() || cls.isDefaultExport()) {
        console.warn(`skipped ${name} (${path.relative(process.cwd(), sourceFile.getFilePath())}): needs a named export`);
        continue;
      }
      const ref = { name, file: sourceFile.getFilePath() };
      if (entry) entry.impls.push(ref);
      if (providerKey) contextProviders.set(providerKey, [...(contextProviders.get(providerKey) ?? []), ref]);
    }
  }
}

function importPath(file: string) {
  const rel = path.relative(outDir, file).split(path.sep).join('/').replace(/\.ts$/, importExt);
  return rel.startsWith('.') ? rel : `./${rel}`;
}

// PaymentHandler -> PAYMENT_HANDLER_LIST / PAYMENT_HANDLER_CONTEXT
function tokenName(interfaceName: string, suffix: 'LIST' | 'CONTEXT') {
  const snake = interfaceName.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2');
  return `${snake.toUpperCase()}_${suffix}`;
}

const angular = target === 'angular';
const entries = [...registry.values()].sort((a, b) => a.iface.name.localeCompare(b.iface.name));
const reserved = new Set([...entries.flatMap((e) => e.impls.map((i) => i.name)), ...[...contextProviders.values()].flat().map((p) => p.name)]);
if (angular) for (const name of ['InjectionToken', 'Provider', 'inject']) reserved.add(name);

const typeImports = new TypeImports(reserved);
// interfaces first, so that no dispatcher import can rebind an interface name
for (const { iface } of entries) {
  const error = typeImports.add(importPath(iface.file), iface.name);
  if (error) {
    console.error(`cannot generate: ${error}`);
    process.exit(1);
  }
}
const valueImports: string[] = [];
const exports: string[] = [];
const providers: string[] = [];
const contextProviderLines = new Map<string, string>(); // provider class -> its useClass line, emitted once
const contextLines: string[] = [];
const dispatcherProviders: string[] = [];
const dispatchers = new Map<string, string>(); // interface name -> dispatcher class name

for (const { iface, impls, decl, marker } of entries) {
  impls.sort((a, b) => a.name.localeCompare(b.name));
  for (const impl of impls) valueImports.push(`import { ${impl.name} } from '${importPath(impl.file)}';`);
  // same shape as Angular's Type<T>, so it can be used directly as `useClass`
  exports.push(
    `export const ${iface.name}Implementations: Array<new (...args: any[]) => ${iface.name}> = [${impls.map((i) => i.name).join(', ')}];`,
  );

  const listToken = tokenName(iface.name, 'LIST');
  if (angular) {
    exports.push(`export const ${listToken} = new InjectionToken<${iface.name}[]>('${listToken}');`);
    // a multi token without any provider would throw on inject(), so fall back to []
    if (impls.length === 0) providers.push(`    { provide: ${listToken}, useValue: [] },`);
    for (const impl of impls) providers.push(`    { provide: ${listToken}, useClass: ${impl.name}, multi: true },`);
  }

  if (!marker) continue;
  const analysis = analyzeDispatcher(decl, marker, importPath, reserved);
  if (!analysis.ok && analysis.fatal) {
    console.error(`cannot generate: ${analysis.reason}`);
    process.exit(1);
  }
  const reason = analysis.ok ? typeImports.merge(analysis.model.imports) : analysis.reason;
  if (!analysis.ok || reason) {
    console.warn(`no dispatcher for ${iface.name}: ${reason}`);
    continue;
  }
  const { model } = analysis;
  dispatchers.set(iface.name, model.className);
  const contextToken = tokenName(iface.name, 'CONTEXT');
  if (angular) {
    dispatcherProviders.push(`    { provide: ${model.className}, useClass: ${model.className} },`);
    if (model.contextType !== undefined) {
      exports.push(`export const ${contextToken} = new InjectionToken<() => ${model.contextType}>('${contextToken}');`);
      const candidates = (contextProviders.get(contextKey(marker.getTypeArguments()[0]) ?? '') ?? []).sort((a, b) => a.name.localeCompare(b.name));
      if (candidates.length > 1) {
        console.warn(`several context providers for ${model.contextType}: ${candidates.map((c) => c.name).join(', ')}; provide ${contextToken} yourself`);
      } else if (candidates[0]) {
        const provider = candidates[0];
        if (!contextProviderLines.has(provider.name)) {
          valueImports.push(`import { ${provider.name} } from '${importPath(provider.file)}';`);
          contextProviderLines.set(provider.name, `    { provide: ${provider.name}, useClass: ${provider.name} },`);
        }
        contextLines.push(
          `    { provide: ${contextToken}, useFactory: () => { const provider = inject(${provider.name}); return () => provider.get(); } },`,
        );
      }
    }
  }
  exports.push('', ...renderDispatcher(model, target, { list: listToken, context: contextToken }), '');
}

if (angular) {
  exports.push(
    '',
    'export function provideImplscan(): Provider[] {',
    '  return [',
    ...providers,
    ...contextProviderLines.values(),
    ...contextLines,
    ...dispatcherProviders,
    '  ];',
    '}',
  );
}

const imports: string[] = [];
if (angular) imports.push(`import { InjectionToken, type Provider${dispatchers.size ? ', inject' : ''} } from '@angular/core';`);
imports.push(...typeImports.render(), ...valueImports);
const runtime = dispatchers.size ? ['', ...RESOLVE_DELEGATE_SOURCE] : [];

const content = [`${GENERATED_HEADER} – do not edit`, ...imports, ...runtime, '', ...exports, '']
  .join('\n')
  .replace(/\n{3,}/g, '\n\n');

if (args['dry-run']) {
  console.log(content);
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, content);
  for (const { iface, impls } of entries) {
    const dispatcher = dispatchers.has(iface.name) ? ` → ${dispatchers.get(iface.name)}` : '';
    console.log(`${iface.name}: ${impls.map((i) => i.name).join(', ') || '(none)'}${dispatcher}`);
  }
  console.log(`wrote ${path.relative(process.cwd(), outFile)}`);
}
