#!/usr/bin/env node
// Scores a run: regenerates, builds, runs visible + acceptance tests, then checks expect.json.
// usage: score.mjs <scenario> <run-dir>   prints JSON
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { listFiles, readJson, scenarioDir, sh } from './lib.mjs';

const [scenario, runDir] = process.argv.slice(2);
const run = resolve(runDir);
const dir = scenarioDir(scenario);
const expect = readJson(join(dir, 'expect.json'));
const checks = [];
const check = (name, pass, detail = '') => checks.push({ name, pass: Boolean(pass), ...(detail ? { detail } : {}) });

const sources = () => listFiles(join(run, 'src')).filter((f) => f.endsWith('.ts'));
const read = (f) => readFileSync(f, 'utf8');
const isGenerated = (text) => text.includes('GENERATED by ts-implscan');
const registries = () => sources().filter((f) => isGenerated(read(f)));

// regeneration: the committed file must match, and warnings count
const pkg = readJson(join(run, 'package.json'));
const usesGenerator = sources().some((f) => /extends\s+(Dispatchable|ImplScan)\b/.test(read(f)));
let generatorWarnings = [];
if (usesGenerator) {
  check('package.json has a generate script', pkg.scripts?.generate);
  if (pkg.scripts?.generate) {
    const before = registries().map((f) => [f, read(f)]);
    const gen = sh('npm run --silent generate', run);
    check('generator exits 0', gen.ok, gen.ok ? '' : gen.out.slice(-1500));
    generatorWarnings = gen.out.split('\n').filter((l) => /^(no dispatcher for|several context providers|skipped )/.test(l));
    check('generator prints no warnings', generatorWarnings.length === 0, generatorWarnings.join('; '));
    check('committed registry is up to date', before.length > 0 && before.every(([f, text]) => existsSync(f) && read(f) === text));
  }
}

// build, with stats for the bundle check
rmSync(join(run, 'dist'), { recursive: true, force: true });
const build = sh('npx ng build --stats-json', run);
check('ng build passes', build.ok, build.ok ? '' : build.out.slice(-2000));

// visible tests plus the hidden acceptance tests, added only for scoring
const hidden = join(run, 'src/app/__acceptance__');
rmSync(hidden, { recursive: true, force: true });
if (existsSync(join(dir, 'acceptance'))) {
  mkdirSync(hidden, { recursive: true });
  cpSync(join(dir, 'acceptance'), hidden, { recursive: true });
}
const report = join(run, '.score-tests.json');
rmSync(report, { force: true });
const test = sh(`npx ng test --no-watch --reporters=json --output-file="${report}"`, run);
rmSync(hidden, { recursive: true, force: true });
const results = existsSync(report) ? readJson(report) : undefined;
rmSync(report, { force: true });
const failures = [];
for (const file of results?.testResults ?? []) {
  const name = relative(run, file.name);
  if (file.status === 'failed' && !file.assertionResults?.length) failures.push(`${name}: ${String(file.message).slice(0, 400)}`);
  for (const a of file.assertionResults ?? []) {
    if (a.status === 'failed') failures.push(`${name} > ${a.title}: ${String(a.failureMessages?.[0] ?? '').split('\n')[0].slice(0, 300)}`);
  }
}
check('all tests pass', test.ok && results, failures.join('\n') || (test.ok ? '' : test.out.slice(-1500)));

// structural expectations
const app = sources().filter((f) => !isGenerated(read(f)) && !f.endsWith('.spec.ts'));
const hasDispatchable = () => app.some((f) => /extends\s+Dispatchable\b/.test(read(f)));
const hasDispatcher = () => registries().some((f) => /export class \w+Dispatcher\b/.test(read(f)));
if (expect.requireDispatcher) {
  check('interface extends Dispatchable', hasDispatchable());
  check('a dispatcher class is generated', hasDispatcher());
}
if (expect.forbidDispatchable) {
  const baseline = sh('git grep -lE "extends +Dispatchable" HEAD -- src', run).out.trim();
  check('no Dispatchable introduced', !baseline && !hasDispatchable());
}
for (const rule of expect.forbid ?? []) {
  const hits = app.filter((f) => new RegExp(rule.pattern).test(read(f)) && (!rule.file || relative(run, f).includes(rule.file)));
  check(rule.name, hits.length === 0, hits.map((f) => relative(run, f)).join(', '));
}

for (const rule of expect.registryContains ?? []) {
  check(rule.name, registries().some((f) => new RegExp(rule.pattern).test(read(f))));
}

// implementations are only reached through the list or the dispatcher, and exist once
const implementations = registries().flatMap((f) => [...read(f).matchAll(/useClass: (\w+), multi: true/g)].map((m) => m[1]));
if (implementations.length) {
  const direct = new RegExp(`(inject|injector\\.get)\\((${implementations.join('|')})\\)`);
  const rootProvided = new RegExp(`providedIn:\\s*'root'[^]*class (${implementations.join('|')})\\b`);
  check('no direct injection of implementations', !app.some((f) => direct.test(read(f))), app.filter((f) => direct.test(read(f))).map((f) => relative(run, f)).join(', '));
  check('implementations are not root-provided too', !app.some((f) => rootProvided.test(read(f))), app.filter((f) => rootProvided.test(read(f))).map((f) => relative(run, f)).join(', '));
}

// a marker must not be reachable from main through static imports
if (expect.notInInitialBundle?.length && build.ok) {
  const statsFile = listFiles(join(run, 'dist'), new Set()).find((f) => f.endsWith('-stats.json'));
  const outputs = readJson(statsFile).outputs;
  const root = Object.keys(outputs).find((k) => /(^|\/)main-[^/]*\.js$/.test(k));
  const initial = new Set();
  const walk = (k) => {
    if (initial.has(k) || !outputs[k]) return;
    initial.add(k);
    for (const i of outputs[k].imports ?? []) if (i.kind === 'import-statement') walk(i.path);
  };
  walk(root);
  const browser = statsFile.replace(/-stats\.json$/, '');
  const text = [...initial].map((k) => read(join(browser, k.split('/').pop()))).join('\n');
  for (const marker of expect.notInInitialBundle) check(`${marker} not in initial bundle`, !text.includes(marker));
}

const diff = sh('git status --short -- . ":(exclude)dist" ":(exclude).angular"', run).out.trim();
console.log(JSON.stringify({ scenario, pass: checks.every((c) => c.pass), failed: checks.filter((c) => !c.pass), passed: checks.filter((c) => c.pass).map((c) => c.name), changed: diff.split('\n') }, null, 2));
